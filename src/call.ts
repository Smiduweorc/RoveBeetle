// The values the generator bakes into each tool function and the protocol
// clients read. They are UTCP call templates after the generator has checked
// them and filled in every default the spec defines, so the runtime never
// guesses: a field that is absent here is absent in the manual and has no
// spec default.
//
// Strings may hold `${NAME}` or `$NAME`. Which fields are substituted is fixed
// per protocol in `variables.ts`.

/** The call template types UTCP 1.1 defines. */
export type Protocol =
	| "http"
	| "sse"
	| "streamable_http"
	| "graphql"
	| "websocket"
	| "tcp"
	| "udp"
	| "mcp"
	| "cli"
	| "text"
	| "file";

/** `api_key` auth. `location` and `name` default to `header` and `X-Api-Key` in the spec. */
export interface ApiKeyAuth {
	readonly type: "api_key";
	readonly key: string;
	readonly name: string;
	readonly location: "header" | "query" | "cookie";
}

/** `basic` auth, sent as `Authorization: Basic`. */
export interface BasicAuth {
	readonly type: "basic";
	readonly username: string;
	readonly password: string;
}

/** `oauth2` auth: the client credentials grant against `tokenUrl`. */
export interface OAuth2Auth {
	readonly type: "oauth2";
	readonly tokenUrl: string;
	readonly clientId: string;
	readonly clientSecret: string;
	readonly scope?: string;
}

export type Auth = ApiKeyAuth | BasicAuth | OAuth2Auth;

/** Fields every request-shaped HTTP template shares. */
interface HttpRequestFields {
	/** May contain `{arg}` placeholders in its path, filled from arguments. */
	readonly url: string;
	/** The `{arg}` placeholders the generator found in the path, so nothing else is read as one. */
	readonly pathFields: readonly string[];
	readonly headers: Readonly<Record<string, string>>;
	/** The one argument sent as the body. */
	readonly bodyField?: string;
	/** Arguments sent as headers, under their own names. */
	readonly headerFields: readonly string[];
	readonly auth?: Auth;
}

export interface HttpTemplate extends HttpRequestFields {
	readonly method: "GET" | "POST" | "PUT" | "DELETE" | "PATCH";
	readonly contentType: string;
}

/**
 * How a text payload becomes a value. The generator picks it from the result
 * schema: `text` when it is a string, `json` when it is anything else, `auto`
 * when the manual gives no schema.
 */
export type DataFormat = "json" | "text" | "auto";

export interface SseTemplate extends HttpRequestFields {
	/** Only events of this type are yielded. Absent: only `message` events. */
	readonly eventType?: string;
	readonly dataFormat: DataFormat;
}

export interface StreamableHttpTemplate extends HttpRequestFields {
	readonly method: "GET" | "POST";
	readonly contentType: string;
}

export interface GraphqlTemplate {
	readonly url: string;
	readonly operationType: "query" | "mutation" | "subscription";
	readonly operationName?: string;
	/** The full document, from the manual or generated by the generator. Never substituted. */
	readonly query: string;
	readonly headers: Readonly<Record<string, string>>;
	readonly headerFields: readonly string[];
	readonly auth?: Auth;
}

export interface WebSocketTemplate {
	readonly url: string;
	/** Message template with `UTCP_ARG_<name>_UTCP_ARG` placeholders. Absent: the arguments as JSON. */
	readonly message?: string | Readonly<Record<string, unknown>>;
	/** The argument names the generator found as placeholders in `message`. */
	readonly messageFields: readonly string[];
	readonly protocol?: string;
	/** Absent: the raw message, a string or bytes. */
	readonly responseFormat?: "json" | "text" | "raw";
	readonly headers: Readonly<Record<string, string>>;
	readonly headerFields: readonly string[];
	readonly auth?: Auth;
}

/** How a TCP response is cut out of the stream. */
export type TcpFraming =
	| { readonly strategy: "length_prefix"; readonly bytes: 1 | 2 | 4 | 8; readonly endian: "big" | "little" }
	| { readonly strategy: "delimiter"; readonly delimiter: string }
	| { readonly strategy: "fixed_length"; readonly length: number }
	| { readonly strategy: "stream"; readonly maxResponseSize: number };

interface SocketFields {
	readonly host: string;
	readonly port: number;
	readonly requestFormat: "json" | "text";
	/** Text template with `UTCP_ARG_<name>_UTCP_ARG` placeholders, for `text` requests. */
	readonly requestTemplate?: string;
	/** The argument names the generator found as placeholders in `requestTemplate`. */
	readonly requestFields: readonly string[];
	/** Encoding the response bytes are decoded with. `null`: raw bytes. */
	readonly responseEncoding: string | null;
}

export interface TcpTemplate extends SocketFields {
	readonly framing: TcpFraming;
}

export interface UdpTemplate extends SocketFields {
	readonly datagrams: number;
}

export type McpServer =
	| {
			readonly transport: "stdio";
			readonly command: string;
			readonly args: readonly string[];
			readonly env: Readonly<Record<string, string>>;
			readonly cwd?: string;
	  }
	| {
			readonly transport: "http";
			readonly url: string;
			readonly headers: Readonly<Record<string, string>>;
	  };

export interface McpTemplate {
	/** The key under `mcpServers`, resolved at generate time. */
	readonly serverName: string;
	readonly server: McpServer;
	/** The tool's name on the server, without the server prefix. */
	readonly toolName: string;
	/** Set when the tool reads a resource rather than calling a tool. */
	readonly resourceUri?: string;
	readonly auth?: OAuth2Auth;
	/** How a result's single text content becomes a value. */
	readonly dataFormat: DataFormat;
	/**
	 * The tool's output schema carries FastMCP's `x-fastmcp-wrap-result`, so
	 * `structuredContent` is `{ "result": value }` and `value` is the result.
	 */
	readonly unwrapResult: boolean;
}

export interface CliCommand {
	/** Shell text with `UTCP_ARG_<name>_UTCP_END` placeholders. Never substituted. */
	readonly command: string;
	/** Whether this command's output is part of the result. */
	readonly appendToFinalOutput: boolean;
}

export interface CliTemplate {
	readonly commands: readonly CliCommand[];
	/** How the trimmed output becomes the result. */
	readonly dataFormat: DataFormat;
	readonly envVars: Readonly<Record<string, string>>;
	/** Host variables passed through. Absent: the spec's safe allowlist. Empty: none. */
	readonly inheritEnvVars?: readonly string[];
	readonly workingDir?: string;
}

export interface TextTemplate {
	/** Returned as the result. Never substituted. */
	readonly content: string;
}

export interface FileTemplate {
	readonly path: string;
}

/** The template type each protocol reads. */
export interface TemplateOf {
	readonly http: HttpTemplate;
	readonly sse: SseTemplate;
	readonly streamable_http: StreamableHttpTemplate;
	readonly graphql: GraphqlTemplate;
	readonly websocket: WebSocketTemplate;
	readonly tcp: TcpTemplate;
	readonly udp: UdpTemplate;
	readonly mcp: McpTemplate;
	readonly cli: CliTemplate;
	readonly text: TextTemplate;
	readonly file: FileTemplate;
}

declare const resultType: unique symbol;
declare const variableNames: unique symbol;

/**
 * One call to one tool, as a plain value. Building one does no I/O.
 *
 * `TResult` is what the client resolves to, unchecked at run time. `TVariables`
 * names every variable the template needs; a client constructed without one
 * of them does not accept this call, so a missing credential fails to
 * compile.
 */
export interface ToolCall<TProtocol extends Protocol, TResult, TVariables extends string = never> {
	readonly protocol: TProtocol;
	/** The tool's name in the manual. */
	readonly tool: string;
	readonly template: TemplateOf[TProtocol];
	readonly args: Readonly<Record<string, unknown>>;

	/** Type-level only; never set. */
	readonly [resultType]?: TResult;
	/**
	 * Type-level only; never set. Covariant, so a call needing `"A"` is
	 * assignable where `"A" | "B"` are available and not the other way round.
	 */
	readonly [variableNames]?: TVariables;
}

/** The result type a {@link ToolCall} resolves to. */
export type ResultOf<T> = T extends ToolCall<Protocol, infer TResult, string> ? TResult : never;

/**
 * Values for the variables a client's calls need, keyed by name.
 *
 * Each is required and must be non-empty. Read them wherever your program keeps
 * secrets; this package never reads the environment.
 */
export type Variables<TVariables extends string> = Readonly<Record<TVariables, string>>;

/** Per-call options every client takes. */
export interface CallOptions {
	/**
	 * Cancels the call. The call rejects with the signal's `reason`, unchanged.
	 * This is also how a call gets a timeout: `AbortSignal.timeout(ms)`.
	 */
	readonly signal?: AbortSignal;
}
