import type { Auth, Protocol } from "../../src/call.js";
import type { Plan, PlannedTool } from "./plan.js";
import { compare } from "./order.js";

// Writes the source a reader opens. Every string from the manual reaches the
// output through `JSON.stringify` or `comment`, never through interpolation
// into code: the manual may come from a server you do not control.

/** Marks a file as this generator's to overwrite. */
export const BANNER_MARK = "@generated by rove beetle";

/** Each protocol's subpath file and client class. */
export const SUBPATHS: Readonly<Record<Protocol, { readonly file: string; readonly client: string }>> = {
	http: { file: "http", client: "HttpClient" },
	sse: { file: "sse", client: "SseClient" },
	streamable_http: { file: "streamable-http", client: "StreamableHttpClient" },
	graphql: { file: "graphql", client: "GraphqlClient" },
	websocket: { file: "websocket", client: "WebSocketClient" },
	tcp: { file: "tcp", client: "TcpClient" },
	udp: { file: "udp", client: "UdpClient" },
	mcp: { file: "mcp", client: "McpClient" },
	cli: { file: "cli", client: "CliClient" },
	text: { file: "text", client: "TextClient" },
	file: { file: "file", client: "FileClient" },
};

/** The modules to write, keyed by file name under `src/tools/`. */
export function emitTools(plan: Plan, source: string): Map<string, string> {
	const modules = new Map<string, string>();
	for (const protocol of plan.protocols) {
		const tools = plan.tools.filter((tool) => tool.tool.protocol === protocol);
		modules.set(`${SUBPATHS[protocol].file}.ts`, emitModule(protocol, tools, source));
	}
	return modules;
}

function emitModule(protocol: Protocol, tools: readonly PlannedTool[], source: string): string {
	const blocks = [
		[
			`// ${BANNER_MARK} from ${comment(source)}. Do not edit.`,
			"//",
			"// Re-running the generator rewrites this file. Call these tools with",
			`// ${SUBPATHS[protocol].client} from the package's ./${SUBPATHS[protocol].file} subpath.`,
		].join("\n"),
		// Every tool has an Args type, so the schema module is always imported.
		["import type { ToolCall } from \"../call.js\";", "import type { components } from \"../schema.js\";"].join("\n"),
		...tools.map(emitTool),
	];
	return `${blocks.join("\n\n")}\n`;
}

function emitTool(tool: PlannedTool): string {
	const args = `${tool.stem}Args`;
	const result = tool.result.kind === "schema" ? `${tool.stem}Result` : tool.result.text;
	const variables = tool.variables.length === 0 ? "" : `, ${tool.variables.map((name) => JSON.stringify(name)).join(" | ")}`;
	const template = literal(tool.tool.template, "\t\t");

	return [
		`/** The arguments of \`${comment(tool.tool.name)}\`. */`,
		`export type ${args} = components["schemas"]["${args}"];`,
		...(tool.result.kind === "schema"
			? ["", `/** What \`${comment(tool.tool.name)}\` resolves to, unchecked at run time. */`, `export type ${result} = components["schemas"]["${result}"];`]
			: []),
		"",
		docComment(tool),
		`export function ${tool.name}(args: ${args}${tool.argsRequired ? "" : " = {}"}): ToolCall<${JSON.stringify(tool.tool.protocol)}, ${result}${variables}> {`,
		"\treturn {",
		`\t\tprotocol: ${JSON.stringify(tool.tool.protocol)},`,
		`\t\ttool: ${JSON.stringify(tool.tool.name)},`,
		`\t\ttemplate: ${template},`,
		"\t\targs,",
		"\t};",
		"}",
	].join("\n");
}

function docComment(tool: PlannedTool): string {
	const { client } = SUBPATHS[tool.tool.protocol];
	const methods = tool.methods.map((method) => `\`${client}.${method}()\``).join(" or ");
	const lines = [
		...(tool.tool.description.trim().length > 0 ? [...tool.tool.description.trim().split(/\r?\n/u), ""] : []),
		`\`${tool.tool.name}\` over ${tool.tool.protocol}. Send it with ${methods}.`,
		...(tool.variables.length > 0 ? [`Needs the variables ${tool.variables.map((name) => `\`${name}\``).join(", ")}.`] : []),
		...authLine((tool.tool.template as { auth?: Auth }).auth),
		...tool.tool.notes,
	];
	return ["/**", ...lines.map((line) => (line.length === 0 ? " *" : ` * ${comment(line)}`)), " */"].join("\n");
}

function authLine(auth: Auth | undefined): string[] {
	if (auth === undefined) {
		return [];
	}
	switch (auth.type) {
	case "api_key":
		return [`Auth: an api key in the ${auth.location} ${JSON.stringify(auth.name)}.`];
	case "basic":
		return ["Auth: HTTP Basic."];
	case "oauth2":
		return [`Auth: OAuth2 client credentials from ${auth.tokenUrl}${auth.scope === undefined ? "" : `, scope ${JSON.stringify(auth.scope)}`}, sent as Bearer.`];
	}
}

/**
 * A value as a TypeScript object literal, written as a person would: keys
 * unquoted where they are identifiers, short lists of scalars on one line,
 * trailing commas. Every string goes through `JSON.stringify`.
 */
export function literal(value: unknown, indent: string): string {
	if (value === null || typeof value !== "object") {
		return JSON.stringify(value);
	}
	const inner = `${indent}\t`;
	if (Array.isArray(value)) {
		if (value.length === 0) {
			return "[]";
		}
		if (value.every((item) => item === null || typeof item !== "object")) {
			const inline = `[${value.map((item) => JSON.stringify(item)).join(", ")}]`;
			if (inline.length <= 60) {
				return inline;
			}
		}
		return `[\n${value.map((item) => `${inner}${literal(item, inner)},`).join("\n")}\n${indent}]`;
	}
	const entries = Object.entries(value).filter(([, item]) => item !== undefined);
	if (entries.length === 0) {
		return "{}";
	}
	const key = (name: string): string => (/^[A-Za-z_$][A-Za-z0-9_$]*$/u.test(name) ? name : JSON.stringify(name));
	return `{\n${entries.map(([name, item]) => `${inner}${key(name)}: ${literal(item, inner)},`).join("\n")}\n${indent}}`;
}

/** Text that is safe inside a line or block comment: no `*\/`, no line breaks. */
export function comment(text: string): string {
	return text.replaceAll("*/", "*\\/").replace(/[\r\n\u2028\u2029]/gu, " ");
}

/** Everything the generated modules export, sorted so a re-run gives a readable diff. */
export function exportsOf(plan: Plan): { values: readonly string[]; types: readonly string[] } {
	return {
		values: plan.tools.map((tool) => tool.name).sort(compare),
		types: plan.tools.flatMap((tool) => [`${tool.stem}Args`, ...(tool.result.kind === "schema" ? [`${tool.stem}Result`] : [])]).sort(compare),
	};
}
